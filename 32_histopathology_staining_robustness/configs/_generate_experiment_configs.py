#!/usr/bin/env python
"""Generate one explicit YAML per ablation cell from ``base_config.yaml``.

Why generate instead of hand-write?  The 13 cells differ only in a handful of
keys (backbone / normalisation / augmentation / batch shape).  Deriving them
mechanically from a single base removes the class of bug where ``EXP-07`` and
``EXP-08`` silently differ in something they were not supposed to (e.g. a
different learning rate), which would break the controlled comparison the whole
ablation rests on.

The generated files are committed to the repo, so a Kaggle session never needs to
run this script -- it exists for provenance and for regenerating the matrix after
a base-config change::

    python configs/_generate_experiment_configs.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT / "src") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "src"))

from histo_robust.utils.config import deep_update, load_config  # noqa: E402

REGISTRY = REPO_ROOT / "configs" / "experiments_registry.json"
EXPERIMENTS_DIR = REPO_ROOT / "configs" / "experiments"

#: Per-cell overrides on top of base_config.yaml.  Only the axes under test may
#: appear here -- everything else stays at the base value on purpose.
CELL_OVERRIDES: Dict[str, Dict[str, Any]] = {
    "EXP-01": {"stage": "Stage 0", "model": {"backbone": "resnet50"}, "normalization": {"name": "none"}, "augmentation": {"policy": "none"}},
    "EXP-02": {"stage": "Stage 1", "model": {"backbone": "resnet50"}, "normalization": {"name": "reinhard"}, "augmentation": {"policy": "none"}},
    "EXP-03": {"stage": "Stage 1", "model": {"backbone": "resnet50"}, "normalization": {"name": "macenko"}, "augmentation": {"policy": "none"}},
    "EXP-04": {"stage": "Stage 2", "model": {"backbone": "resnet50"}, "normalization": {"name": "none"}, "augmentation": {"policy": "aug_geo"}},
    "EXP-05": {"stage": "Stage 2", "model": {"backbone": "resnet50"}, "normalization": {"name": "none"}, "augmentation": {"policy": "aug_stain"}},
    "EXP-06": {"stage": "Stage 2", "model": {"backbone": "resnet50"}, "normalization": {"name": "none"}, "augmentation": {"policy": "aug_combined"}},
    "EXP-07": {"stage": "Stage 3", "model": {"backbone": "resnet50"}, "normalization": {"name": "macenko"}, "augmentation": {"policy": "aug_geo"}},
    "EXP-08": {"stage": "Stage 3", "model": {"backbone": "resnet50"}, "normalization": {"name": "macenko"}, "augmentation": {"policy": "aug_stain"}},
    "EXP-09": {"stage": "Stage 3", "model": {"backbone": "resnet50"}, "normalization": {"name": "macenko"}, "augmentation": {"policy": "aug_combined"}},
    "EXP-10": {"stage": "Stage 4", "model": {"backbone": "convnext_tiny"}, "normalization": {"name": "none"}, "augmentation": {"policy": "none"}},
    "EXP-11": {"stage": "Stage 4", "model": {"backbone": "convnext_tiny"}, "normalization": {"name": "macenko"}, "augmentation": {"policy": "aug_combined"}},
    # Phikon is a ViT-B/16: batch 32 with 2 accumulation steps == the ResNet
    # effective batch of 64 (docs/PLAN.md section 5, "Batch Size & Gradient Accumulation").
    "EXP-12": {
        "stage": "Stage 4",
        "model": {"backbone": "phikon", "freeze_backbone": True, "dropout": 0.0},
        "normalization": {"name": "none"},
        "augmentation": {"policy": "none"},
        "data": {"batch_size": 32},
        "train": {"grad_accum_steps": 2},
    },
    "EXP-13": {
        "stage": "Stage 4",
        "model": {"backbone": "phikon", "freeze_backbone": True, "dropout": 0.0},
        "normalization": {"name": "macenko"},
        "augmentation": {"policy": "aug_combined"},
        "data": {"batch_size": 32},
        "train": {"grad_accum_steps": 2},
    },
}

HEADER = """# ---------------------------------------------------------------------------
# {exp_id} -- {stage}
# GENERATED by configs/_generate_experiment_configs.py from base_config.yaml.
# Do not hand-edit: change base_config.yaml or CELL_OVERRIDES and regenerate, so
# every cell stays identical outside the axis it is meant to test.
#
# This file is deliberately SELF-CONTAINED (the full merged config is written
# out): it carries no `_base_` key, so what you read here is exactly what runs,
# and two cells can be diffed directly.  `_overrides_` records the delta from
# base_config.yaml for provenance only.  Regenerate after editing the base.
#
# Research question : {question}
# Comparator        : {comparator}
# Backbone          : {backbone}
# Normalization     : {normalization}
# Augmentation      : {augmentation}
# ---------------------------------------------------------------------------
"""


def main() -> int:
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))["experiments"]
    base = load_config(REPO_ROOT / "configs" / "base_config.yaml", repo_root=REPO_ROOT)
    base.pop("_config_path", None)
    base.pop("_config_name", None)

    EXPERIMENTS_DIR.mkdir(parents=True, exist_ok=True)
    written = []
    for entry in registry:
        exp_id = entry["exp_id"]
        overrides = CELL_OVERRIDES.get(exp_id, {})
        cfg = deep_update(dict(base), overrides)
        cfg["exp_id"] = exp_id
        cfg["stage"] = overrides.get("stage", entry.get("stage", ""))
        cfg["research_question"] = entry.get("research_question", "")
        cfg["comparator"] = entry.get("comparator", "")
        cfg["_base_source_"] = "configs/base_config.yaml"
        cfg["_overrides_"] = overrides

        target = REPO_ROOT / entry["config"]
        header = HEADER.format(
            exp_id=exp_id,
            stage=entry.get("stage", ""),
            question=entry.get("research_question", ""),
            comparator=entry.get("comparator", ""),
            backbone=cfg["model"]["backbone"],
            normalization=cfg["normalization"]["name"],
            augmentation=cfg["augmentation"]["policy"],
        )
        body = yaml.safe_dump(cfg, sort_keys=False, default_flow_style=False, allow_unicode=True)
        target.write_text(header + body, encoding="utf-8")
        written.append(str(target.relative_to(REPO_ROOT)))
        print(f"wrote {target.relative_to(REPO_ROOT)}")

    print(f"\n{len(written)} experiment configs generated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
